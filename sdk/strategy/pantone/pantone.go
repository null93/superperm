func Generate(alphabet string) string {
	n := len(alphabet)
	if n < 8 {
		result := standard.Generate(alphabet)
		if other := egan.Generate(alphabet); len(other) < len(result) {
			result = other
		}
		return result
	}
	seed, starts := eightSeed(), []string(nil)
	if n == 9 {
		seed, starts = nineSeed(), nineStarts
	}
	for k := len(seed[0].X) + 1; k < n-1; k++ {
		seed = selection.Transport(seed, k, uint8(k))
	}
	word := selection.Join(selection.Complete(seed, n, uint8(n-1)), n, starts)
	return selection.Relabel(word, alphabet)
}

func eightSeed() []selection.Slice {
	return selection.Walk("012345", eight+eight)
}

func nineSeed() []selection.Slice {
	seed := append(selection.Walk("0123456", nineA), selection.Walk("0126435", nineB)...)
	for _, x := range nineFull {
		seed = append(seed, selection.Slice{X: selection.Digits(x), S: 7, Classes: 0})
	}
	return seed
}
